/** Id of the virtual module the Vite plugin serves. */
export const VIRTUAL_ID = 'virtual:mask-icons'

/** Group of the icons at the top of an icon folder, and of `<mask-icon>` by default. */
export const DEFAULT_GROUP = 'core'

/**
 * Renders the declarations for the virtual module, the icon names of each
 * group and the variant values, so `<mask-icon group name variant>`
 * autocompletes and rejects unknown values.
 */
export const renderTypes = (groups: Record<string, { icons: string[] }>, variantValues: string[] = []) => `// Generated by mask-icons. Do not edit.
declare module '${VIRTUAL_ID}' {
  /** Sprite URL of each icon group. */
  export const sprites: Record<string, string>
  /** Groups whose sprite is preloaded. */
  export const preload: string[]
  /** Icon names of each group. */
  export const icons: Record<string, string[]>
  /** Variant axes, their defaults and the variants built per icon, or null without variants. */
  export const variants: import('svg-mask-icons/vue').MaskIconVariantManifest | null
}

declare module 'svg-mask-icons/vue' {
  interface MaskIconRegistry {
${Object.entries(groups).map(([group, { icons }]) => `    ${JSON.stringify(group)}: ${icons.map((name) => JSON.stringify(name)).join(' | ') || 'never'}`).join('\n')}
  }
  interface MaskIconVariantRegistry {
${variantValues.map((value) => `    ${JSON.stringify(value)}: true`).join('\n')}
  }
}

export {}
`
